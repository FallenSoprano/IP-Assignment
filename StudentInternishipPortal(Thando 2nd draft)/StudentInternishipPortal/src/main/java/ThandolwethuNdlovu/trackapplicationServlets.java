    /**
     * Handles the HTTP <code>GET</code> method.
     *
     * @param request servlet request
     * @param response servlet response
     * @throws ServletException if a servlet-specific error occurs
     * @throws IOException if an I/O error occurs
     */
    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        String username = (String) request.getSession().getAttribute("username");
    
        ArrayList<String[][]> myapplications = new ArrayList<>(); 
        
        if (username != null){
            for (String[][] application:applyServlet.applications){
               for (String[] rows : application){
                        if (username.equals(rows[0])){
                            myapplications.add(application);
                        }  
                       
                }
                
            }
        }
        
        request.setAttribute("applications",myapplications);
        RequestDispatcher rd = request.getRequestDispatcher("trackapplications.jsp");
            rd.forward(request, response);
    }

